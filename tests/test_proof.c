static int g_pass = 0, g_fail = 0;

#define CHECK(cond, msg)                                                       \
    do {                                                                       \
        if (cond) {                                                            \
            printf("  PASS: %s\n", msg);                                       \
            g_pass++;                                                          \
        } else {                                                               \
            printf("  FAIL: %s (line %d)\n", msg, __LINE__);                   \
            g_fail++;                                                          \
        }                                                                      \
    } while (0)

/* Build a small AND circuit: x0 AND x1 = x2 (witness only)
 *   witness[0] = x0, witness[1] = x1, witness[2] = x0 AND x1
 *   assert_zero(x0 AND x1 XOR x2)  → trivially satisfied if x2 = x0&x1
 *   But more simply: just assert x0 AND x1 = x2 by constraining the output.
 *
 * We build: w0 = witness_bit(0), w1 = witness_bit(1)
 *           w2 = AND(w0, w1)     ← AND gate output is w2
 *   No explicit constraint needed: the AND gate output already IS the
 *   correct value by definition of the circuit evaluation.
 *
 *   Actually for a meaningful proof we need to constrain something.
 *   Let's make a circuit that proves knowledge of (a, b) such that
 *   (a AND b) XOR c = 0 where c is an instance bit.
 *
 *   Instance: c = a & b (public target)
 *   Witness: a, b
 *   Circuit:
 *     w0 = witness(0) = a
 *     w1 = witness(1) = b
 *     w2 = AND(w0, w1) = a & b
 *     w3 = instance(0) = c
 *     w4 = XOR(w2, w3) = (a&b) XOR c
 *     assert_zero(w4)
 */
static voleith_circuit_t *
build_and_circuit(void)
{
    voleith_circuit_t *c = voleith_circuit_new();
    if (!c)
        return NULL;

    wire_id w0 = voleith_circuit_add_witness(c);     /* a */
    wire_id w1 = voleith_circuit_add_witness(c);     /* b */
    wire_id w2 = voleith_circuit_add_and(c, w0, w1); /* a & b */
    wire_id w3 = voleith_circuit_add_instance(c);    /* c (public) */
    wire_id w4 = voleith_circuit_add_xor(c, w2, w3); /* (a&b) XOR c */
    voleith_circuit_assert_zero(c, w4);

    return c;
}

/* Build a slightly larger circuit with a chain of AND gates */
static voleith_circuit_t *
build_chain_circuit(int n_and)
{
    voleith_circuit_t *c = voleith_circuit_new();
    if (!c)
        return NULL;

    /* Add 2 witness bits: a, b */
    wire_id a = voleith_circuit_add_witness(c);
    wire_id b = voleith_circuit_add_witness(c);

    /* Chain: w = a & b, w = w & a, w = w & b, ... */
    wire_id w = voleith_circuit_add_and(c, a, b);
    for (int i = 1; i < n_and; i++) {
        wire_id next = (i % 2 == 0) ? voleith_circuit_add_and(c, w, a)
                                    : voleith_circuit_add_and(c, w, b);
        w = next;
    }

    /* Assert the final result is zero (forces a=0 or b=0) */
    voleith_circuit_assert_zero(c, w);

    return c;
}

