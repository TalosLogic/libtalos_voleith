/* ================================================================
 * X-7 regression: voleith_params_validate rejects every documented
 * malformed parameter shape, accepts the predefined parameter sets.
 * ================================================================ */

static void
test_params_validate(void)
{
    CHECK(voleith_params_validate(NULL) != 0, "X-7: NULL params rejected");

    /* All predefined static parameter sets must pass. */
    CHECK(voleith_params_validate(&voleith_params_em_128s) == 0,
          "X-7: em_128s accepted");
    CHECK(voleith_params_validate(&voleith_params_em_128f) == 0,
          "X-7: em_128f accepted");
    CHECK(voleith_params_validate(&voleith_params_em_192s) == 0,
          "X-7: em_192s accepted");
    CHECK(voleith_params_validate(&voleith_params_em_192f) == 0,
          "X-7: em_192f accepted");
    CHECK(voleith_params_validate(&voleith_params_em_256s) == 0,
          "X-7: em_256s accepted");
    CHECK(voleith_params_validate(&voleith_params_em_256f) == 0,
          "X-7: em_256f accepted");

    voleith_params_t p;

    /* Bad lambda. */
    p = voleith_params_em_128f;
    p.lambda = 64;
    CHECK(voleith_params_validate(&p) != 0, "X-7: lambda=64 rejected");
    p.lambda = 129;
    CHECK(voleith_params_validate(&p) != 0, "X-7: lambda=129 rejected");
    p.lambda = 0;
    CHECK(voleith_params_validate(&p) != 0, "X-7: lambda=0 rejected");

    /* Bad tau. */
    p = voleith_params_em_128f;
    p.tau = 0;
    CHECK(voleith_params_validate(&p) != 0, "X-7: tau=0 rejected");
    p.tau = 33;
    CHECK(voleith_params_validate(&p) != 0,
          "X-7: tau=33 rejected (exceeds i_delta[32])");
    p.tau = UINT_MAX;
    CHECK(voleith_params_validate(&p) != 0, "X-7: tau=UINT_MAX rejected");

    /* Bad w_grind. */
    p = voleith_params_em_128f;
    p.w_grind = p.lambda;
    CHECK(voleith_params_validate(&p) != 0,
          "X-7: w_grind == lambda rejected");
    p.w_grind = p.lambda + 1;
    CHECK(voleith_params_validate(&p) != 0, "X-7: w_grind > lambda rejected");
    p.w_grind = UINT_MAX;
    CHECK(voleith_params_validate(&p) != 0, "X-7: w_grind=UINT_MAX rejected");

    /* Bad n_leafcom. */
    p = voleith_params_em_128f;
    p.n_leafcom = 0;
    CHECK(voleith_params_validate(&p) != 0, "X-7: n_leafcom=0 rejected");
    p.n_leafcom = 1;
    CHECK(voleith_params_validate(&p) != 0, "X-7: n_leafcom=1 rejected");
    p.n_leafcom = 4;
    CHECK(voleith_params_validate(&p) != 0, "X-7: n_leafcom=4 rejected");

    /* Bad T_open. */
    p = voleith_params_em_128f;
    p.T_open = 0;
    CHECK(voleith_params_validate(&p) != 0, "X-7: T_open=0 rejected");
}

/* X-7: confirm the public prove / verify entry points surface the
 * validation failure with a clean -1, not a deep-cascade rejection. */
static void
test_params_validate_at_api_boundary(void)
{
    voleith_circuit_t *c = voleith_circuit_new();
    wire_id w = voleith_circuit_add_witness(c);
    voleith_circuit_assert_zero(c, w);

    uint8_t witness[1] = {0};
    uint8_t fs_seed[16] = {0};

    voleith_params_t bad = voleith_params_em_128f;
    bad.tau = 0; /* Invalid */

    size_t blob_size = voleith_commit_blob_size(&voleith_params_em_128f, c);
    uint8_t *blob = calloc(blob_size, 1);

    voleith_prover_commit_t *ctx = NULL;
    int rc = voleith_prove_commit(&ctx, &bad, c, witness, NULL, fs_seed,
                                  sizeof(fs_seed), blob);
    CHECK(rc != 0, "X-7: voleith_prove_commit rejects invalid params");

    voleith_proof_t proof = {NULL, voleith_proof_byte_size(
                                       &voleith_params_em_128f,
                                       voleith_qs_ell(c))};
    proof.data = calloc(proof.len, 1);
    voleith_verifier_reconstruct_t *vctx = NULL;
    int rc2 = voleith_verify_reconstruct(&vctx, &proof, &bad, c, blob);
    CHECK(rc2 != 0, "X-7: voleith_verify_reconstruct rejects invalid params");

    free(proof.data);
    free(blob);
    voleith_circuit_free(c);
}

