/* ================================================================
 * Test: proof_byte_size matches actual proof
 * ================================================================ */

static void
test_proof_size(void)
{
    printf("\n[proof_byte_size]\n");

    voleith_circuit_t *c = build_and_circuit();
    if (!c) {
        printf("  SKIP: circuit alloc failed\n");
        return;
    }

    size_t ell = voleith_qs_ell(c);
    size_t computed = voleith_proof_byte_size(&voleith_params_em_128f, ell);

    /* Prove and check actual size */
    uint8_t witness[1] = {0};  /* a=0, b=0 → a&b=0, c=0 → valid */
    uint8_t instance[1] = {0}; /* c=0 */
    uint8_t fs_seed[16];
    memset(fs_seed, 0x42, sizeof(fs_seed));

    voleith_proof_t proof;
    memset(&proof, 0, sizeof(proof));
    int ret = voleith_prove(&proof, &voleith_params_em_128f, c, witness,
                            instance, fs_seed, sizeof(fs_seed));

    if (ret != 0) {
        printf("  FAIL: prove returned %d (line %d)\n", ret, __LINE__);
        g_fail++;
    } else {
        CHECK(proof.len == computed,
              "Proof size matches voleith_proof_byte_size");
        voleith_proof_free(&proof);
    }

    voleith_circuit_free(c);
}

/* ================================================================
 * Test: AND circuit prove + verify
 * ================================================================ */

static void
test_and_circuit_roundtrip(const voleith_params_t *params, const char *label)
{
    printf("\n[AND circuit roundtrip: %s]\n", label);

    voleith_circuit_t *c = build_and_circuit();
    if (!c) {
        printf("  SKIP: circuit alloc failed\n");
        return;
    }

    /* Witness: a=1, b=1 → a&b=1; instance c=1 → (a&b) XOR c = 0 ✓ */
    uint8_t witness[1] = {0x03};  /* bits: a=1, b=1 */
    uint8_t instance[1] = {0x01}; /* c=1 */
    uint8_t fs_seed[16];
    memset(fs_seed, 0xAB, sizeof(fs_seed));

    voleith_proof_t proof;
    memset(&proof, 0, sizeof(proof));
    int pret = voleith_prove(&proof, params, c, witness, instance, fs_seed,
                             sizeof(fs_seed));
    CHECK(pret == 0, "Prove succeeds");

    if (pret == 0) {
        int vret = voleith_verify(&proof, params, c, instance, fs_seed,
                                  sizeof(fs_seed));
        CHECK(vret == 0, "Valid proof verifies");
        voleith_proof_free(&proof);
    }

    voleith_circuit_free(c);
}

/* ================================================================
 * Test: Wrong witness is rejected
 * ================================================================ */

static void
test_wrong_witness_rejected(void)
{
    printf("\n[wrong witness rejected]\n");

    const voleith_params_t *params = &voleith_params_em_128f;
    voleith_circuit_t *c = build_and_circuit();
    if (!c) {
        printf("  SKIP: circuit alloc failed\n");
        return;
    }

    /* Correct witness: a=1, b=0, c=0 → (1&0) XOR 0 = 0 ✓ */
    uint8_t witness_ok[1] = {0x01}; /* a=1, b=0 */
    uint8_t instance[1] = {0x00};   /* c=0 */
    /* Wrong witness: a=1, b=1, but c=0 → (1&1) XOR 0 = 1 ✗ */
    uint8_t witness_bad[1] = {0x03}; /* a=1, b=1 */
    uint8_t fs_seed[16];
    memset(fs_seed, 0x77, sizeof(fs_seed));

    /* X-10: the bit-level prover now rejects an invalid witness
     * up-front (matching the GF(2⁸) discipline) - voleith_prove must
     * return non-zero and must not publish a proof.  Defense-in-
     * depth: even if the prover ever regresses to publish a bad
     * proof, the verifier still rejects it.
     */
    voleith_proof_t proof;
    memset(&proof, 0, sizeof(proof));

    int pret = voleith_prove(&proof, params, c, witness_bad, instance, fs_seed,
                             sizeof(fs_seed));
    CHECK(pret != 0, "X-10: prove with wrong witness is rejected upfront");
    if (pret == 0) {
        /* Should not be reached under the current contract, but if
         * the prover ever publishes a bad proof, the verifier still
         * catches it. */
        int vret = voleith_verify(&proof, params, c, instance, fs_seed,
                                  sizeof(fs_seed));
        CHECK(vret != 0, "verify rejects bad-witness proof (fallback)");
        voleith_proof_free(&proof);
    }

    /* Sanity: a correct witness still proves and verifies. */
    memset(&proof, 0, sizeof(proof));
    pret = voleith_prove(&proof, params, c, witness_ok, instance, fs_seed,
                         sizeof(fs_seed));
    CHECK(pret == 0, "Prove with correct witness succeeds");
    if (pret == 0) {
        int vret2 = voleith_verify(&proof, params, c, instance, fs_seed,
                                   sizeof(fs_seed));
        CHECK(vret2 == 0, "Correct witness verifies");
        voleith_proof_free(&proof);
    }

    voleith_circuit_free(c);
}

/* ================================================================
 * Test: Modified proof is rejected
 * ================================================================ */

static void
test_tamper_detection(void)
{
    printf("\n[tamper detection]\n");

    const voleith_params_t *params = &voleith_params_em_128f;
    voleith_circuit_t *c = build_and_circuit();
    if (!c) {
        printf("  SKIP: circuit alloc failed\n");
        return;
    }

    uint8_t witness[1] = {0x03};  /* a=1, b=1 */
    uint8_t instance[1] = {0x01}; /* c=1 */
    uint8_t fs_seed[16];
    memset(fs_seed, 0x55, sizeof(fs_seed));

    voleith_proof_t proof;
    memset(&proof, 0, sizeof(proof));
    int pret = voleith_prove(&proof, params, c, witness, instance, fs_seed,
                             sizeof(fs_seed));
    if (pret != 0) {
        printf("  SKIP: prove failed\n");
        voleith_circuit_free(c);
        return;
    }

    /* Verify clean proof passes */
    CHECK(voleith_verify(&proof, params, c, instance, fs_seed,
                         sizeof(fs_seed)) == 0,
          "Clean proof verifies before tampering");

    /* Test one byte from each logical proof section to confirm the verifier
     * actually checks every component. The Fiat-Shamir hash guarantee means
     * any change in a checked section propagates to chall_3 mismatch. */
    size_t proof_len = proof.len;
    uint8_t *proof_data = proof.data;
    int all_rejected = 1;

    /* Compute section offsets matching proof_layout() in proof.c */
    unsigned int nb = params->lambda / 8;
    size_t ell = voleith_qs_ell(c);
    size_t ellhat = voleith_qs_ellhat(c, params->lambda);
    size_t ellhat_bytes = (ellhat + 7) / 8;
    size_t ell_bytes = (ell + 7) / 8;
    size_t utilde_bytes = nb + 2; /* VOLEITH_VOLE_HASH_B = 2 */
    size_t decom_size =
        params->n_leafcom * params->tau * nb + params->T_open * nb;
    size_t off_c = 0;
    size_t off_utilde = off_c + (params->tau - 1) * ellhat_bytes;
    size_t off_d = off_utilde + utilde_bytes;
    size_t off_a1 = off_d + ell_bytes;
    size_t off_a2 = off_a1 + nb;
    size_t off_decom = off_a2 + nb;
    size_t off_chall3 = off_decom + decom_size;
    size_t off_iv = off_chall3 + nb;
    size_t off_ctr = off_iv + 16;

    /* One byte per section */
    size_t positions[] = {
        off_c,      /* c[0]: VOLE correction values */
        off_utilde, /* u_tilde: compressed VOLE */
        off_d,      /* d: witness correction (only if ell_bytes > 0) */
        off_a1,     /* a1_tilde: QS degree-1 hash */
        off_a2,     /* a2_tilde: QS degree-2 hash */
        off_decom,  /* decom_i: BAVC opening */
        off_chall3, /* chall_3: grinding challenge */
        off_iv,     /* iv: PRG initialisation vector */
        off_ctr,    /* ctr: grinding counter */
    };

    for (size_t pi = 0; pi < sizeof(positions) / sizeof(positions[0]); pi++) {
        size_t p = positions[pi];
        if (p >= proof_len)
            continue; /* section absent for this circuit */

        uint8_t orig = proof_data[p];
        proof_data[p] ^= 0xFF;

        voleith_proof_t tampered = {proof_data, proof_len};
        int vret = voleith_verify(&tampered, params, c, instance, fs_seed,
                                  sizeof(fs_seed));
        if (vret == 0) {
            printf("  FAIL: byte at section offset %zu not rejected\n", p);
            all_rejected = 0;
        }

        proof_data[p] = orig;
    }

    CHECK(all_rejected, "Each proof section byte is rejected when tampered");

    voleith_proof_free(&proof);
    voleith_circuit_free(c);
}

/* ================================================================
 * Test: Different fs_seeds give different but valid proofs
 * ================================================================ */

static void
test_different_seeds(void)
{
    printf("\n[different fs_seeds]\n");

    const voleith_params_t *params = &voleith_params_em_128f;
    voleith_circuit_t *c = build_and_circuit();
    if (!c) {
        printf("  SKIP\n");
        return;
    }

    uint8_t witness[1] = {0x03};
    uint8_t instance[1] = {0x01};
    uint8_t seed1[16], seed2[16];
    memset(seed1, 0x11, sizeof(seed1));
    memset(seed2, 0x22, sizeof(seed2));

    voleith_proof_t p1, p2;
    memset(&p1, 0, sizeof(p1));
    memset(&p2, 0, sizeof(p2));

    int r1 =
        voleith_prove(&p1, params, c, witness, instance, seed1, sizeof(seed1));
    int r2 =
        voleith_prove(&p2, params, c, witness, instance, seed2, sizeof(seed2));

    CHECK(r1 == 0 && r2 == 0, "Both proves succeed");

    if (r1 == 0 && r2 == 0) {
        CHECK(p1.len == p2.len, "Proof sizes match");
        CHECK(memcmp(p1.data, p2.data, p1.len) != 0,
              "Different seeds → different proofs");
        CHECK(voleith_verify(&p1, params, c, instance, seed1, sizeof(seed1)) ==
                  0,
              "Proof 1 verifies with seed1");
        CHECK(voleith_verify(&p2, params, c, instance, seed2, sizeof(seed2)) ==
                  0,
              "Proof 2 verifies with seed2");
        /* Cross-verify should fail */
        CHECK(voleith_verify(&p1, params, c, instance, seed2, sizeof(seed2)) !=
                  0,
              "Proof 1 rejected with seed2");
        voleith_proof_free(&p1);
        voleith_proof_free(&p2);
    }

    voleith_circuit_free(c);
}

